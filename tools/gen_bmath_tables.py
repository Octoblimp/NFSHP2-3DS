"""Emit 3DS Files/source/bmathtab.c from the four bMath data tables in the ELF.

These are shipped data, not code, so the port carries the bytes rather than a
model of them. Three of the four *do* regenerate from a formula (see
docs/formats/bmath.md) and this script checks that they still do, so a bad
read of the ELF cannot pass silently. bSinTable has no known generator and is
copied verbatim.

    python tools/gen_bmath_tables.py            # write the file
    python tools/gen_bmath_tables.py --check    # verify it is up to date
"""
import math
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mipsdis

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "3DS Files", "source", "bmathtab.c")

# The float32 rounding of 32768/pi, which is what the tables were built with.
RAD_TO_BAM = 10430.3779296875

ASIN_TABLE = 0x003152a0      # 209 x {u16 angle; u16 pad; float slope}
SIN_TABLE = 0x00315928       # 513 x s16
ATAN_LOW = 0x00315d30        # 129 x u16
ATAN_HIGH = 0x00315e38       # 129 x u16


def asin_bucket_left(idx):
    """The x value, in 1/65536ths, that bASinTable[idx] is the left edge of.

    Straight out of bASin's own arithmetic at 0x002420ac: base is the octave's
    floor, the bucket step is width >> 4. Indices 192 and up come from the
    loop's `oct >= 11` exit, where bucket runs 16..31 against octave 11's base
    rather than 0..15 -- so they are not a thirteenth octave, they are the
    tail of the twelfth.
    """
    oct_, bucket = (11, idx - 176) if idx >= 192 else (idx >> 4, idx & 15)
    width = 0x10000 >> (oct_ + 1)
    base = 0 if oct_ == 0 else 0x10000 - (0x10000 >> oct_)
    return base + bucket * (width >> 4)


def read_tables():
    elf = mipsdis.Elf()

    sin_table = list(struct.unpack("<513h", elf.read(SIN_TABLE, 1026)))
    atan_low = list(struct.unpack("<129H", elf.read(ATAN_LOW, 258)))
    atan_high = list(struct.unpack("<129H", elf.read(ATAN_HIGH, 258)))

    raw = elf.read(ASIN_TABLE, 209 * 8)
    asin_table = [struct.unpack_from("<HHf", raw, i * 8) for i in range(209)]

    # The two atan tables regenerate exactly. If they ever stop, the ELF read
    # is wrong, not the formula.
    for name, tab, scale in (("Low", atan_low, 32.0), ("High", atan_high, 4.0)):
        want = [int(math.atan(i / scale) * RAD_TO_BAM) for i in range(129)]
        if tab != want:
            bad = [i for i in range(129) if tab[i] != want[i]]
            raise SystemExit("bFixATanTable%s does not match its generator at "
                             "%s" % (name, bad[:8]))

    # bASinTable's angle column is asin at the bucket's left edge -- but
    # unlike the atan tables it does NOT regenerate exactly. 208 of the 209
    # entries are int(asin(lo / 65536) * RAD_TO_BAM); index 160 is not,
    # because asin(65472/65536) * RAD_TO_BAM lands 1.2e-4 BAM below 15923 in
    # double and the original's asin was a shade less precise, so it stored
    # 15923 where the model truncates to 15922. That is one entry, it is
    # documented, and the table ships verbatim either way -- so this is a
    # bound check, not a regeneration. It is still tight enough to catch a
    # misread stride or a wrong base address, which is the point.
    #
    # The slope column is close to the secant across the bucket but not equal
    # to it (up to 3.5e-4 relative), so it only gets a range check.
    for idx, (angle, pad, slope) in enumerate(asin_table):
        want = math.asin(min(1.0, asin_bucket_left(idx) / 65536.0)) * RAD_TO_BAM
        if abs(angle - want) > 1.0 or pad != 0 or not (0.15 < slope < 60.0):
            if idx != 208:      # the terminator, never read
                raise SystemExit("bASinTable[%d] looks wrong: %r vs %.2f"
                                 % (idx, asin_table[idx], want))

    if sin_table[128] != 32767 or sin_table[384] != -32768 or sin_table[512] != 0:
        raise SystemExit("bSinTable landmarks are wrong: %r"
                         % [sin_table[i] for i in (128, 384, 512)])

    return sin_table, atan_low, atan_high, asin_table


def rows(values, per, fmt):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + " ".join(fmt % v for v in values[i:i + per]))
    return "\n".join(out).rstrip()


def f32(x):
    # Shortest decimal that round-trips through float32.
    for digits in range(1, 10):
        s = "%.*g" % (digits, x)
        if struct.unpack("<f", struct.pack("<f", float(s)))[0] == x:
            return s + "f"
    return repr(x) + "f"


def render():
    sin_table, atan_low, atan_high, asin_table = read_tables()
    parts = []
    parts.append("""\
// bmathtab -- the four bMath lookup tables, lifted out of NFSHP2.ELF.
//
// GENERATED by tools/gen_bmath_tables.py. Do not edit; re-run the script.
//
// These are shipped data. bFixATanTableLow/High regenerate exactly as
//     (int)(atan(i / s) * 10430.3779296875)
// -- double atan, truncated, times the float32 rounding of 32768/pi, not
// 32768/pi itself; the single entry atan(1.0) is what tells the two apart.
// The generator script re-derives them on every run and refuses to emit a
// file that disagrees. bSinTable has no known generator and is copied byte
// for byte; see docs/formats/bmath.md.
#include "bmath.h"

// sin over one turn in 512 steps, Q15. bFixSin doubles each entry on the way
// out, so a value of 1.0 leaves this table as 65534, not 65536.
const int16_t bSinTable[513] = {
%s
};

// asin, twelve octaves of sixteen buckets -- plus a sixteen-entry tail.
// `angle` is the BAM angle at the bucket's left edge and `slope` is roughly
// the secant slope across it, in turns per unit x; bASin multiplies by 65536
// to land back in BAM.
//
// Indices 0..191 are the twelve octaves. 192..207 are what bASin reads when
// its octave walk stops on the `oct >= 11` guard instead of on a comparison,
// which happens for x >= 0.99976: bucket then runs 16..31 against octave
// eleven's base. 208 is a terminator and is never read.
const BASinEntry bASinTable[209] = {
%s
};

// atan of a Q16 tangent, in BAM. Low covers tan 0..4 at 1/32 steps, High
// covers 0..32 at 1/4 steps but is only entered from index 16 up.
const uint16_t bFixATanTableLow[129] = {
%s
};

const uint16_t bFixATanTableHigh[129] = {
%s
};
""" % (rows(sin_table, 10, "%6d,"),
       "\n".join("    { %5d, %s }," % (a, f32(s)) for a, _p, s in asin_table),
       rows(atan_low, 10, "%6d,"),
       rows(atan_high, 10, "%6d,")))
    return "".join(parts)


def main():
    text = render()
    check = "--check" in sys.argv
    old = None
    if os.path.exists(OUT):
        with open(OUT, "r", newline="") as fh:
            old = fh.read()
    if check:
        if old == text:
            print("bmathtab.c is up to date")
            return 0
        print("bmathtab.c is STALE -- re-run tools/gen_bmath_tables.py")
        return 1
    with open(OUT, "w", newline="") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (OUT, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
