def s_edges(rnd):
    """The thresholds one at a time."""
    out = []
    base = ["S np 1", "PL 0 0 0 0", "PL 1 0 0 1", "S nrc 2", "WL 0 1",
            "AD 0 1"]
    # The countdown's boundaries: each count's length, the GO's 60 frames,
    # the cop's longer count.
    for cop in (0, 1):
        for t in (0, 53, 54, 55, 59, 60, 107, 108, 109, 161, 162, 163, 215,
                  216, 217, 240):
            out.append(base + ["S beacop %d" % cop, "S cdt 1000",
                               "S wtf %d" % (1000 + t), "GN", "GP", "DN 1",
                               "DN 3"])
        for t in (0, 59, 60, 61, 62):
            out.append(base + ["S beacop %d" % cop, "S cdt 900", "S go 1000",
                               "S wtf %d" % (1000 + t), "GN", "GP", "DN 4",
                               "DN 0"])
    # The GO's sample either side of 0.8.
    for t in (0, 100, 150, 172, 173, 200):
        out.append(base + ["S cdt 1000", "S go 1162",
                           "S wtf %d" % (1000 + t), "DN 4"])
    # The finish: equal times, one player not finished, the animation's
    # last frame.
    for t0, t1, a, w in ((100, 100, 10, 111), (100, 100, 10, 110),
                         (100, 0, 10, 200), (0, 100, 10, 200),
                         (100, 90, 5, 106), (100, 90, 5, 105),
                         (-5, 10, 0, 11), (-5, -3, 0, 100)):
        out.append(base + ["S np 2", "PL 0 %d %d 0" % (t0, a),
                           "PL 1 %d %d 1" % (t1, a), "S wtf %d" % w,
                           "S state 3", "S begun 1", "AA", "MR", "C 3 3 0"])
    # What comes next.
    for another in (0, 1):
        for multi in (0, 1):
            out.append(base + ["S state 3", "S another %d" % another,
                               "S multi %d" % multi, "RF"])
    # The flyby and the prerace TICK with no camera, which the port reads
    # as finished.
    for flyfin in (0, 1):
        out.append(base + ["S state 1", "S fly 0", "S flyfin %d" % flyfin,
                           "C 1 3 0", "M 3 0", "E"])
    for pfin in (0, 1):
        out.append(base + ["S state 2", "S pre 0", "S pfin %d" % pfin,
                           "S stage 2", "C 2 3 0", "E"])
    # A message answered by a message, answered by a change of state.
    out.append(base + ["S state 3", "R 7 1 S 9 1", "R 0 1 P 3 0",
                       "S np 1", "PL 0 100 0 0", "S wtf 200", "C 3 3 0",
                       "E"])
    return out


def script():
    rnd = random.Random(0x8f57a7e5)
    sc = []
    sc += s_countdown(rnd, 60)
    sc += s_finish(rnd, 40)
