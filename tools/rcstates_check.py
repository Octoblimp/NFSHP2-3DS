    def call(self, fn, *args):
        e = self.e
        sp = e.reg[29] & M32
        e.write(sp - 0x4000, bytes(0x4000))
        return e.call(fn, *args, limit=2000000)

    def op(self, t):
        e = self.e
        c = t[0]
        if c == "S":
            self.set_global(t[1], int(t[2], 0))
            return
        if c == "R":
            self.react.append((int(t[1]), int(t[2]), t[3], int(t[4], 0),
                               int(t[5], 0)))
            return
        n = [int(x, 0) for x in t[1:]]
        if c == "PL":
            p = player_at(n[0])
            e.put32(p + P_TIME, n[1])
            e.put32(p + P_ANIM, n[2])
            e.put32(p + P_CAR, car_at(n[3]) if n[3] >= 0 else 0)
            return
        if c == "K":
            struct.pack_into("<h", e.mem, rcar_at(n[0]) + RCAR_REASON, n[1])
            struct.pack_into("<b", e.mem, rcar_at(n[0]) + RCAR_POS, n[2])
            return
        if c == "WL":
            e.put32(WORLD, WORLD)
            e.put32(WORLD + 4, WORLD)
            for k in n:
                car = car_at(k)
                tail = self.w(WORLD + 4)
                e.put32(car + 4, tail)
                e.put32(car, WORLD)
                e.put32(tail, car)
                e.put32(WORLD + 4, car)
            return
        if c == "AD":
            e.put32(car_at(n[0]) + C_DRIVER, driver_at(n[0]) if n[1] else 0)
            return
        if c == "FD":
            e.write(FED_DISPLAY, bytes(v & 0xff for v in n))
            return

        rc = RCBUF
        if c == "M":
            self.call(SEND, rc, n[0], n[1])
        elif c == "P":
            self.call(POST, rc, n[0], n[1])
        elif c == "E":
            self.call(EXECUTE, rc)
        elif c == "T":
            self.call(CHANGE_STATE, rc, n[0])
        elif c == "C":
            r = self.call(CBS[n[0]], rc, n[1], n[2])
            self.emit("  ret %d" % r)
        elif c == "DN":
            self.call(DISPLAY, rc, n[0])
        elif c == "RF":
            self.call(FINISHED, rc)
        elif c == "J":
            self.call(JOY, 0, n[0], 0, 0)
        elif c == "RP":
            self.call(REQ_PAUSE, rc, n[0])
        elif c == "RU":
            self.call(REQ_UNPAUSE, rc, n[0])
        elif c == "DR":
            self.call(RESUME_DEMO, rc)
        elif c == "DS":
            self.call(SUSPEND_DEMO, rc)
        elif c == "GN":
            self.emit("  number %d" % self.call(NUMBER, RACE))
        elif c == "GP":
            self.call(PROGRESS, RACE)
            self.emit("  progress %s" % fx(e.fpr[0]))
        elif c == "SIM":
            self.call(SIMULATE, RACE)
        elif c == "NOT":
            self.call(NOTIFY, RACE)
        elif c == "AA":
            self.emit("  allfin %d" % self.call(ALL_FINISHED, RACE))
        elif c == "MR":
            self.emit("  recent %s"
                      % self.name(self.call(MOST_RECENT, RACE)))
        else:
            raise SystemExit("bad op %r" % (t,))
        self.dump()

    def run(self, scenarios):
        for i, sc in enumerate(scenarios):
            self.emit("B %d" % i)
            self.reset()
            for ln in sc:
                self.emit("> " + ln[:40])
                self.op(ln.split())
        return self.out


