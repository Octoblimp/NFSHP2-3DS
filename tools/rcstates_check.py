    def queue(self, rc):
        w = self.w
        lst = rc + RC_LIST
        fwd = []
        p = w(lst)
        while p != lst and len(fwd) < 80:
            fwd.append(" %s:%d/%d" % (self.name(p), s32(w(p + 8)),
                                      s32(w(p + 12))))
            p = w(p)
        back = []
        p = w(lst + 4)
        while p != lst and len(back) < 80:
            back.append(" " + self.name(p))
            p = w(p + 4)
        return "".join(fwd) + " |" + "".join(back)

    def reset(self):
        e = self.e
        self.nobj = 0
        self.slot_used = [False] * NSLOT
        self.fill(RCBUF, RC_BYTES)
        e.put32(RCBUF + RC_STATE, 0)
        e.put32(RCBUF + RC_LIST, RCBUF + RC_LIST)
        e.put32(RCBUF + RC_LIST + 4, RCBUF + RC_LIST)
        e.put32(RCBUF + RC_EXEC, 0)
        for off in (16, 20, 24):
            e.put32(RCBUF + off, 0)
        for off in (28, 32, 36, 40):
            e.put32(RCBUF + off, 0)
        for o in (FLY, PRE, DEMO, EG):
            e.write(o, bytes(256))
            e.put32(o + 24, FAKE_VT)
        e.put32(PRE + PRE_FINISHED, 1)
        self.fill(RACE, 0x800)
        for off in (R_STAGE, R_GO, R_COUNTDOWN, R_NRC):
            e.put32(RACE + off, 0)
        for k in range(NRC):
            self.fill(rcar_at(k), RCAR_STRIDE)
            e.put32(RACE + R_RACINGCARS + 4 * k, rcar_at(k))
        for i in range(2):
            self.fill(player_at(i), 0x100)
            e.put32(player_at(i) + P_CAR, 0)
            e.put32(player_at(i) + P_TIME, 0)
            e.put32(player_at(i) + P_ANIM, 0)
            e.put32(G_BY_INDEX + 4 * i, player_at(i))
        e.put32(G_NUM, 0)
        self.fill(WORLD, 0x100)
        e.put32(WORLD, WORLD)
        e.put32(WORLD + 4, WORLD)
        for k in range(NCAR):
            self.fill(car_at(k), CAR_STRIDE)
            e.put32(car_at(k) + C_DRIVER, 0)
        self.fill(REPLAY, 0x100)
        e.put32(REPLAY + 92, 0)
        for k in range(3):
            self.fill(flobj_at(k), 64)
            e.mem[flobj_at(k) + OBJ_VIS] = 0
        e.write(FED_DISPLAY, bytes(8))
        e.write(RP_DISPLAY, bytes(8))
        e.put32(G_RC, RCBUF)
        e.put32(G_RACE, RACE)
        e.put32(G_WORLD, WORLD)
        e.put32(G_REPLAY, REPLAY)
        e.put32(G_POOL, POOL)
        e.put32(G_WTF, 0)
        e.put32(G_JBTIMER, JB_START)
        e.put32(RP_NPLAYCARS, 1)
        e.put32(RP_BEACOP, 0)
        self.t = {"flyfin": 1, "pfin": 1, "prerace": 0, "playing": 0,
                  "nosample": 0, "noobj": 0, "another": 0, "multi": 0,
                  "fcdrop": 0, "rdrop": 0,
                  "initstate": -1}
        self.react = []

    def set_global(self, f, v):
        e = self.e
        regs = {"state": RCBUF + RC_STATE, "exec": RCBUF + RC_EXEC,
                "port": RCBUF + 20, "bp": RCBUF + 24,
                "beacop": RP_BEACOP, "nplaycars": RP_NPLAYCARS,
                "wtf": G_WTF, "stage": RACE + R_STAGE, "go": RACE + R_GO,
                "cdt": RACE + R_COUNTDOWN, "nrc": RACE + R_NRC,
                "np": G_NUM, "begun": REPLAY + 92}
        if f in regs:
            e.put32(regs[f], v & M32)
        elif f in self.t:
            self.t[f] = v
            if f == "pfin":
                pre = self.w(RCBUF + 36)
                if pre:
                    e.put32(pre + PRE_FINISHED, v)
        elif f in ("vis3", "vis2", "vis1"):
            e.mem[flobj_at(3 - int(f[3])) + OBJ_VIS] = v & 0xff
        elif f in ("fly", "pre", "demo", "eg"):
            off = {"fly": 32, "pre": 36, "demo": 28, "eg": 40}[f]
            obj = {"fly": FLY, "pre": PRE, "demo": DEMO, "eg": EG}[f]
            e.put32(RCBUF + off, obj if v else 0)
            if f == "pre" and v:
                e.put32(PRE + PRE_FINISHED, self.t["pfin"])
        else:
            raise SystemExit("bad global %s" % f)

