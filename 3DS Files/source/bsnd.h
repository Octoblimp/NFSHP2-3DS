#pragma once
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "sndbank.h"

// bSnd -- the port of the disc's sound driver, over ndsp instead of the SPU2.
//
// The interface and the arithmetic come out of libbsndm.a's bDriverPS2.o; the
// addresses are in docs/formats/sound-driver.md and in the comments below.
// What is kept is everything that decides *what* a voice should sound like --
// which patch, which channels, what left/right volumes, what rate -- because
// that is the part a listener can hear is wrong. What is replaced is the half
// that talked to an SPU2 across an IOP: banks are .SBK files read by
// sndbank.c, and a voice is an ndsp channel.
//
// Everything above the BsndSink line builds on the host, so tools/bsnd_check.py
// can drive it through scripted sequences and diff the transcript against a
// second implementation written from the disassembly. The ndsp half is behind
// __3DS__ at the bottom of bsnd.c and is the only part no checker can reach.

// The PS2 had 48 SPU2 voices (two cores of 24) and bSnd_GetNumberOfVoices()
// returns 48 flat (0x0024bc50). ndsp has 24 channels, so the port's voice
// space is half the size. Nothing else changes: the allocator is the same
// scan, just over a shorter range, and the frontend never asked for more than
// four at once. BSND_PS2_VOICES exists so the checker can run the allocator
// at the original width as well as this one.
#define BSND_MAX_VOICES    24
// What bsnd_hw_init hands the allocator: ndsp's last two channels are the
// EA TRAX stream (JBS_CHANNEL in jbstream.h) and the boot movies' sound
// (AVIMOVIE_CHANNEL in avimovie.h).
#define BSND_HW_VOICES     22
#define BSND_PS2_VOICES    48
#define BSND_MAX_BANKS     8

// Sentinels the original spells as out-of-range values of the real argument.
#define BSND_VOICE_ALLOC   0xffffu       // PS2: 48, i.e. one past the last
#define BSND_RATE_PATCH    0xffffffffu   // use the patch's own Pitch
#define BSND_VOLUME_PATCH  0xffffu       // use the patch's own Volume
#define BSND_PAN_PATCH     (-128)        // use the patch's own Pan

// SOUND_PATCH_INFO::Pan, which bSnd_VoicePlay substitutes for the -128
// sentinel (0x00248f30). It is 0 in all 469 records on the disc, so .SBK does
// not carry the field and this constant stands in for it; audio_pack.py
// refuses to build a bank that would make that untrue.
#define BSND_PATCH_PAN     0

// bSnd_VoicePlay's returns, at the values 0x00247f00 uses.
#define BSND_NO_PATCH      0xfffeu   // no such patch, or no free channels
#define BSND_BAD_VOICE     0xfffcu   // the run would not fit the voice space
#define BSND_PATCH_NONE    0xfffau   // bSnd_GetPatchID: not found

// SOUND_SPUKeyStatus, at the values the low driver writes (0x00250a08,
// 0x00251c44, 0x0024fefc). 1 and 2 are legacy states this disc never writes,
// which is why "free" means 0 and nothing else.
enum { BSND_KEY_OFF = 0, BSND_KEY_ON = 3, BSND_KEY_RELEASE = 4 };

// bSnd_GetMode/bSnd_SetMono/bSnd_SetStereo/bSnd_SetPrologic. Mode below 2
// collapses pan to centre inside GetVolumesFromPan (0x0024d94c), and mode 3
// skips the pan path in bSnd_SetVoiceVolume entirely (0x0024a928).
enum { BSND_MODE_MONO = 1, BSND_MODE_STEREO = 2, BSND_MODE_PROLOGIC = 3 };

// bSnd_nArraydBPanTable, in bsndtab.c. Generated by tools/gen_bsnd_tables.py.
extern const uint16_t bsnd_pan_table[256];

// SOUND_VOICE_INFO (0x00316a50, 80 bytes, the .mdebug layout), minus the
// fields that only meant something to the SPU: Type, ProVol*, and the copies
// of the bank and patch names, which the port replaces with `patch` below.
typedef struct {
    int8_t   pan;            // Pan
    uint8_t  loopChannel;    // LoopChannel -- high nibble is the channel index
    int8_t   streamChannel;  // StreamChannel, -1 when the voice is not a stream
    uint8_t  paused;         // Paused
    uint32_t pitch;          // Pitch, in Hz -- not the SPU register value
    uint16_t volume;         // Volume, 0..0x7fff before panning
    uint16_t effectVolume;   // EffectVolume
    uint16_t azimuth;        // Azimuth
    uint16_t type;           // Type: 4 when placed by azimuth, else loop + 1
    uint32_t adsr;           // ADSR
    uint16_t volL, volR;     // what GetVolumesFromPan last worked out
    uint16_t patch;          // flat patch id, or BSND_PATCH_NONE
} BsndVoice;

// One loaded .SBK. `first` mirrors SOUND_BANK_INFO::StartPatch: patch ids are
// flat across every loaded bank, exactly as bSnd_GetPatchID hands them out.
typedef struct {
    SndBank  bank;
    uint8_t* image;          // NULL when the caller kept ownership
    uint32_t hash;           // bStringHash of the bank name
    uint16_t first;          // StartPatch
    uint16_t count;          // EndPatch - StartPatch
    bool     used;
} BsndBankSlot;

// What the driver asks of a mixer. On the 3DS this is ndsp; in the checker it
// is a recorder. Every call names a voice index, never a patch, because by
// this point the driver has already decided everything.
typedef struct BsndSink {
    // Begin a patch on `ch`. `data`/`bytes` is one channel's DSPADPCM, `coefs`
    // its sixteen coefficients. A looping patch loops the whole buffer -- see
    // docs/formats/sound-bank.md, "Looping patches lose their lead-in".
    void (*start)(void* user, unsigned ch, const uint8_t* data, uint32_t bytes,
                  uint32_t samples, const int16_t* coefs, uint32_t rate,
                  bool looping);
    void (*stop)(void* user, unsigned ch);
    void (*mix)(void* user, unsigned ch, uint16_t left, uint16_t right);
    void (*rate)(void* user, unsigned ch, uint32_t hz);
    void (*pause)(void* user, unsigned ch, bool paused);
    // Whether the mixer still has audio on `ch`. bsnd_update uses it to
    // release voices whose one-shot has run out, which is what
    // bSound::updateCompletedVoices did (0x0025bcf8).
    bool (*playing)(void* user, unsigned ch);
    void* user;
} BsndSink;

typedef struct {
    const BsndSink* sink;
    void* (*alloc)(size_t);      // linearAlloc on the 3DS, malloc on the host
    void  (*release)(void*);
    unsigned voices;             // BSND_MAX_VOICES here, 48 for a PS2-shaped run
    uint8_t  mode;               // BSND_MODE_*
    uint16_t patchCount;         // the flat table's high-water mark
    BsndVoice voice[BSND_PS2_VOICES];
    uint8_t   key[BSND_PS2_VOICES];    // SOUND_SPUKeyStatus
    int8_t    lock[BSND_PS2_VOICES];   // bSnd_LockChannels' table
    BsndBankSlot bankSlot[BSND_MAX_BANKS];
    char      path[160];         // bSnd_SetLoadPath
} BsndDriver;

// -- units -------------------------------------------------------------------

// SOUND_HzToSPU (0x002528b8): the SPU pitch register, where 0x1000 is 48000
// Hz. The port has no such register -- ndsp takes Hz -- but the conversion is
// kept because it is lossy, and a patch that played at 22050 Hz on the disc
// came back out of the divide at 22045.9. Playing the port's sounds at the
// exact Hz would make them slightly sharper than the PS2's.
uint32_t bsnd_hz_to_spu(uint32_t hz);
uint32_t bsnd_spu_to_hz(uint32_t spu);

// GetPanFromAzimuth (0x0024f688). 0 is dead ahead, 0x4000 hard right, 0x8000
// behind, 0xc000 hard left; the result is -127..127 and never -128, which is
// what lets -128 be the "use the patch's pan" sentinel.
int8_t bsnd_pan_from_azimuth(uint16_t azimuth);

// GetAzimuthFromPan (0x0024f7e0), the other way, which is how every overload
// of bSnd_VoicePlay that takes a pan reaches the one that takes an azimuth.
// Single precision on purpose: the EE multiplies with mul.s, and at pan 127
// the double-precision answer truncates one short of hard right.
uint16_t bsnd_azimuth_from_pan(int8_t pan);

// GetVolumesFromPan (0x0024d928), table lookup and 14-bit shift included.
void bsnd_volumes_from_pan(const BsndDriver* d, uint16_t* left, uint16_t* right,
                           uint16_t volume, int8_t pan);

// SOUND_FindFreeSPUChannels (0x002520c0): the lowest run of `count` adjacent
// channels in [first,last] that are neither locked nor sounding. Scans
// downwards when last < first. -1 when there is no such run, -2/-3 when an
// endpoint is out of range.
int bsnd_find_free_channels(const BsndDriver* d, unsigned first, unsigned last,
                            unsigned count);

// -- driver ------------------------------------------------------------------

void bsnd_init(BsndDriver* d, const BsndSink* sink, unsigned voices);
void bsnd_close(BsndDriver* d);
void bsnd_set_mode(BsndDriver* d, uint8_t mode);
void bsnd_set_load_path(BsndDriver* d, const char* path);

// bSnd_BankLoad / bSnd_BankUnload. `name` is the bank's stem, uppercase, as
// the .MSH is named: "COMMON", "FRONTEND". Reads <path>/<NAME>.SBK.
bool bsnd_bank_load(BsndDriver* d, const char* name);
// Registers an image the caller already has. The driver takes ownership only
// when `owned`; the checker passes false and keeps its own buffers.
bool bsnd_bank_register(BsndDriver* d, const char* name, uint8_t* image,
                        size_t size, bool owned);
bool bsnd_bank_unload(BsndDriver* d, const char* name);
bool bsnd_bank_loaded(const BsndDriver* d, const char* name);

// bSnd_GetPatchID (0x0024d730). BSND_PATCH_NONE when either name misses.
uint16_t bsnd_patch_id(const BsndDriver* d, const char* bank, const char* patch);
bool bsnd_patch_get(const BsndDriver* d, uint16_t id, SndPatch* out);
// bSnd_GetPatchChannels: 1, or 2 for a joined stereo pair.
unsigned bsnd_patch_channels(const BsndDriver* d, uint16_t id);

// bSnd_VoicePlay's eight-argument overload (0x00247f00), less the two
// arguments that only fed the SPU's reverb send. There is no pan argument
// because the original has none: placement is an azimuth, and the pan that
// reaches the table is bsnd_pan_from_azimuth of it. `voice` is
// BSND_VOICE_ALLOC to let the driver choose. Returns the first voice used, or
// one of BSND_NO_PATCH / BSND_BAD_VOICE.
uint16_t bsnd_voice_play(BsndDriver* d, const char* bank, const char* patch,
                         uint32_t rate, uint16_t volume, uint16_t azimuth,
                         uint16_t voice);

// The overload at 0x00247a28, which is how the game says "play this at that
// pan": azimuth is bsnd_azimuth_from_pan(pan), and -128 keeps the patch's own.
uint16_t bsnd_voice_play_pan(BsndDriver* d, const char* bank, const char* patch,
                             uint32_t rate, uint16_t volume, int8_t pan,
                             uint16_t voice);

void bsnd_voice_stop(BsndDriver* d, uint16_t voice);
void bsnd_voice_pause(BsndDriver* d, uint16_t voice);
void bsnd_voice_resume(BsndDriver* d, uint16_t voice);
bool bsnd_voice_paused(const BsndDriver* d, uint16_t voice);
bool bsnd_channel_busy(const BsndDriver* d, uint16_t voice);

void bsnd_set_voice_volume(BsndDriver* d, uint16_t voice, uint16_t volume);
void bsnd_set_voice_pan(BsndDriver* d, uint16_t voice, int8_t pan);
void bsnd_set_voice_volume_pan(BsndDriver* d, uint16_t voice, uint16_t volume,
                               int8_t pan);
void bsnd_set_voice_pitch(BsndDriver* d, uint16_t voice, uint32_t hz);

uint16_t bsnd_get_voice_volume(const BsndDriver* d, uint16_t voice);
int8_t   bsnd_get_voice_pan(const BsndDriver* d, uint16_t voice);
uint32_t bsnd_get_voice_pitch(const BsndDriver* d, uint16_t voice);

// bSnd_LockChannels / bSnd_UnlockChannels: a locked channel is invisible to
// the allocator but keeps playing.
void bsnd_lock_channels(BsndDriver* d, uint16_t first, uint16_t count);
void bsnd_unlock_channels(BsndDriver* d, uint16_t first, uint16_t count);

// Once a frame. Clears the key status of any voice the mixer has finished
// with, so the allocator can hand it out again.
void bsnd_update(BsndDriver* d);

// -- the 3DS half ------------------------------------------------------------

