// Opens ndsp, installs the ndsp sink and linearAlloc, and points the driver at
// <data>/SOUND. False when ndsp is unavailable, in which case the game runs
// silent rather than not at all.
bool bsnd_hw_init(BsndDriver* d);
void bsnd_hw_close(BsndDriver* d);
#endif
