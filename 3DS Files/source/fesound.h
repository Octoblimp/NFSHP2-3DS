#pragma once
#include <stdint.h>

#include "bsound.h"

// fesound -- the noises the menu system makes for itself: retail's
// FrontendSoundEvent table (0x002fb098) and the five functions round it,
// on bSound.
//
//   InitGlobalMenuSound   0x0016ded8   InitFlailerMenuSystem's, at boot
//   InitFrontendSounds    0x0016df60   EndGameFlowLoadingFrontEnd's
//   UnInitFrontendSounds  0x0016dff8   BeginGameFlowUnloadingFrontEnd's
//   MakeFrontendSound     0x0016e038   the BMenuSoundFn
//   StopFrontendSound     0x0016e0e8   CarSelector's destructor
//
// bmenu.c raises the events -- BMenuSoundFn, called with
// BScreenCallbackData::noise -- and this is the other end of that hook.
// An entry's sample comes from the common region (the menus' own noises,
// looked up once at boot) or from the "FrontEnd" region (the car
// selector's, the event tree's, the name entry's), looked up each time the
// frontend has loaded and forgotten when it unloads.

#define FESOUND_EVENT_COUNT 31

typedef struct {
    int32_t     id;             // the entry's own FrontendSoundEvent
    int32_t     fromFrontEnd;   // 0: CommonRegion; 1: Region("FrontEnd")
    const char* name;           // NULL for silence
} FeSoundEntry;

// Generated by tools/gen_bsnd_tables.py into bsndtab.c.
extern const FeSoundEntry fesound_events[FESOUND_EVENT_COUNT];

void fesound_init_global(void);         // 0x0016ded8
void fesound_init_frontend(void);       // 0x0016df60
void fesound_uninit_frontend(void);     // 0x0016dff8

// The BMenuSoundFn, installed straight into BMenu::sound. `user` is
// ignored: MakeFrontendSound took only the event, and BMenu::user belongs
// to the screen's own callback. An event with no sample is silence; the
// same sample again within 34 ms is not replayed.
void fesound_play(int soundEvent, void* user);
void fesound_stop(int soundEvent);      // 0x0016e0e8
