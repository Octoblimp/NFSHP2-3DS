#pragma once
#include <stdbool.h>

#include "bsnd.h"

// MakeFrontendSound (0x001692c0) and the table it indexes (0x002f30ac): the
// noises the menu system makes for itself. bmenu.c already raises the events
// -- BMenuSoundFn, called with BScreenCallbackData::noise -- so this is the
// other end of that hook, turning an event into a patch and a voice.
//
// The disc reached the mixer through bSample/bRegion, a layer above bSnd that
// cached a handle per event at init. There is nothing to cache here: a .SBK
// stays in memory once loaded and bsnd_voice_play looks the patch up by hash,
// so the event table is the whole of it.

#define FESOUND_EVENT_COUNT 33

typedef struct {
    const char* bank;    // "COMMON", "FRONTEND", or NULL for silence
    const char* patch;
} FeSoundEntry;

// Generated by tools/gen_bsnd_tables.py into bsndtab.c.
extern const FeSoundEntry fesound_events[FESOUND_EVENT_COUNT];

// Loads the banks the table names from the driver's load path, and remembers
// the driver for fesound_play. Missing banks are not fatal: the events that
// needed them go quiet and the rest still play, which is what a partly
// converted SD card should do.
void fesound_init(BsndDriver* d);

// The BMenuSoundFn, installed straight into BMenu::sound. `user` is ignored:
// MakeFrontendSound took only the event and reached the mixer through a
// global, and BMenu::user belongs to the screen's own callback. Event 0
// (BSND_NONE) is silence, and is the commonest case by a wide margin.
void fesound_play(int soundEvent, void* user);
